CREATE TABLE public.lomba_pendaftaran (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lomba_slug text NOT NULL,
  kategori text NOT NULL,
  nama_lengkap text NOT NULL,
  usia smallint NOT NULL,
  alamat text NOT NULL,
  asal text,
  whatsapp text NOT NULL,
  musik_path text NOT NULL,
  musik_nama text NOT NULL,
  musik_mime text NOT NULL,
  foto_path text NOT NULL,
  foto_mime text NOT NULL,
  status text NOT NULL DEFAULT 'menunggu_bayar',
  catatan text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT lomba_pendaftaran_slug_ok CHECK (lomba_slug = 'pasanggiri-jaipong'),
  CONSTRAINT lomba_pendaftaran_kategori_ok CHECK (kategori IN ('tk', 'sd-1-3', 'sd-4-6', 'smp-sma')),
  CONSTRAINT lomba_pendaftaran_nama_ok CHECK (char_length(btrim(nama_lengkap)) BETWEEN 2 AND 100),
  CONSTRAINT lomba_pendaftaran_usia_ok CHECK (usia BETWEEN 3 AND 25),
  CONSTRAINT lomba_pendaftaran_alamat_ok CHECK (char_length(btrim(alamat)) BETWEEN 5 AND 300),
  CONSTRAINT lomba_pendaftaran_asal_ok CHECK (asal IS NULL OR char_length(asal) <= 100),
  CONSTRAINT lomba_pendaftaran_wa_ok CHECK (char_length(whatsapp) BETWEEN 9 AND 20 AND whatsapp ~ '^[0-9+[:space:]-]+$'),
  CONSTRAINT lomba_pendaftaran_musik_ok CHECK (musik_path LIKE 'musik/%' AND char_length(musik_nama) <= 200),
  CONSTRAINT lomba_pendaftaran_foto_ok CHECK (foto_path LIKE 'foto/%' AND foto_mime IN ('image/jpeg', 'image/png', 'image/webp')),
  CONSTRAINT lomba_pendaftaran_status_ok CHECK (status IN ('menunggu_bayar', 'terkonfirmasi', 'ditolak')),
  CONSTRAINT lomba_pendaftaran_catatan_ok CHECK (catatan IS NULL OR char_length(catatan) <= 500)
);

GRANT SELECT, UPDATE, DELETE ON public.lomba_pendaftaran TO authenticated;
GRANT ALL ON public.lomba_pendaftaran TO service_role;

ALTER TABLE public.lomba_pendaftaran ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins read lomba registrations" ON public.lomba_pendaftaran
  FOR SELECT TO authenticated USING (public.has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins update lomba registrations" ON public.lomba_pendaftaran
  FOR UPDATE TO authenticated USING (public.has_role(auth.uid(), 'admin')) WITH CHECK (public.has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins delete lomba registrations" ON public.lomba_pendaftaran
  FOR DELETE TO authenticated USING (public.has_role(auth.uid(), 'admin'));

-- Kuota 25 peserta per kategori; pendaftar yang ditolak tidak dihitung.
CREATE OR REPLACE FUNCTION public.lomba_cek_kuota()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  terisi integer;
BEGIN
  IF NEW.status = 'ditolak' THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.status <> 'ditolak' AND OLD.kategori = NEW.kategori THEN
    RETURN NEW;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('lomba:' || NEW.lomba_slug || ':' || NEW.kategori));
  SELECT count(*) INTO terisi FROM public.lomba_pendaftaran
   WHERE lomba_slug = NEW.lomba_slug AND kategori = NEW.kategori AND status <> 'ditolak' AND id <> NEW.id;
  IF terisi >= 25 THEN
    RAISE EXCEPTION 'KUOTA_PENUH' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER lomba_pendaftaran_kuota
  BEFORE INSERT OR UPDATE OF status, kategori ON public.lomba_pendaftaran
  FOR EACH ROW EXECUTE FUNCTION public.lomba_cek_kuota();

