#!/usr/bin/env bash
# Rebuilds the GGS Hair Studio visitor site into public/ggs-hair-studio/.
# Usage: bash scripts/ggs-hair-studio/build.sh   (from the project root)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SRC="${GGS_SRC:-/tmp/ggs}"
if [ ! -f "$SRC/artifacts/ggs-visit/package.json" ]; then
  git clone --depth 1 https://github.com/nempocreative/GGS-Hair-Studio-36 "$SRC"
fi
cd "$SRC"
# Start from an untouched checkout or a freshly extracted upstream archive.
if [ -d .git ]; then git restore .; fi
pnpm install --filter "@workspace/ggs-visit..." --ignore-scripts --frozen-lockfile
APP="$SRC/artifacts/ggs-visit"
node "$HERE/patch-logo.mjs" "$APP" "$HERE/brand"
node "$HERE/patch-menu.mjs" "$APP"
node "$HERE/patch-layout.mjs" "$APP"
node "$HERE/patch-whatsapp.mjs" "$APP"
node "$HERE/patch-beranda.mjs" "$APP"
node "$HERE/patch-diskon.mjs" "$APP"
node "$HERE/patch-team.mjs" "$APP"
node "$HERE/patch-booking-models.mjs" "$APP"
node "$HERE/patch-pricelist.mjs" "$APP"
node "$HERE/patch-pricelist-pria.mjs" "$APP"
node "$HERE/patch-swipe.mjs" "$APP"
node "$HERE/patch-my-ggs.mjs" "$APP"
node "$HERE/patch-tab-diskon.mjs" "$APP"
node "$HERE/patch-tab-home-service.mjs" "$APP"
node "$HERE/patch-nail-art-video.mjs" "$APP"
node "$HERE/patch-order-form.mjs" "$APP"
# AI service photos (Indonesian faces) matched to each price list row by pricelist-services.ts.
cp "$HERE"/pricelist-photos/*.jpg "$APP/public/"
cd "$APP"
PORT=5173 BASE_PATH=/ggs-hair-studio/ NODE_ENV=production npx vite build --config vite.config.ts
rm -rf "$ROOT/public/ggs-hair-studio"
cp -R "$APP/dist/public" "$ROOT/public/ggs-hair-studio"
# The original placeholder icons are replaced by the real GGS logo.
rm -f "$ROOT/public/ggs-hair-studio/favicon.svg" "$ROOT/public/ggs-hair-studio/logo.svg"
# Photos and icons are shrunk on the built copy (owner request).
bash "$HERE/optimize-images.sh" "$ROOT/public/ggs-hair-studio"
# A few photos are written as root paths in the original code; point them inside the sub-site.
sed -i -E 's#(["\x27`])/(ggs-carousel-|ai-women-|ai-style-)#\1/ggs-hair-studio/\2#g' "$ROOT"/public/ggs-hair-studio/assets/*.js
# Starting content (studio info, services, products) from the original server's defaults.
node "$HERE/content.mjs" "$SRC/artifacts/api-server/src/routes/ggs.ts" "$ROOT/src/data/ggs-hair-studio-content.json"
# The page shell is served by src/routes/ggs-hair-studio*.tsx so deep links survive a refresh.
node -e '
const fs=require("fs");
const html=fs.readFileSync(process.argv[1],"utf8");
fs.writeFileSync(process.argv[2],"// Generated by scripts/ggs-hair-studio/build.sh — do not edit.\nexport const GGS_HTML = "+JSON.stringify(html)+";\n");
' "$ROOT/public/ggs-hair-studio/index.html" "$ROOT/src/lib/ggs-hair-studio-shell.ts"
# Never leave the shell as a public file: hosting would serve it and skip the code check.
rm -f "$ROOT/public/ggs-hair-studio/index.html"
echo "GGS Hair Studio built into public/ggs-hair-studio"
